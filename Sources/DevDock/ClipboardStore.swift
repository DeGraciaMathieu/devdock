import AppKit

/// Keeps the latest copied texts in memory only; nothing is written to disk.
@MainActor
final class ClipboardStore: ObservableObject {
    @Published private(set) var history: [String] = []

    private let maxEntries = 30
    private let pollInterval: TimeInterval = 0.5
    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?

    /// Markers set by password managers (1Password…) and other apps on copies that must not be recorded,
    /// see nspasteboard.org.
    private let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    init() {
        lastChangeCount = pasteboard.changeCount

        // macOS has no clipboard notification: polling the change counter is the usual way.
        timer = Timer.scheduledTimer(withTimeInterval: pollInterval, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.recordNewCopy() }
        }
    }

    func copy(_ text: String) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
    }

    private func recordNewCopy() {
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: ignoredTypes),
              let text = pasteboard.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }

        // A text copied again moves back to the top instead of being duplicated.
        history.removeAll { $0 == text }
        history.insert(text, at: 0)
        history = Array(history.prefix(maxEntries))
    }
}
